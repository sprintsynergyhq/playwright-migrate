// Generates docs/mapping.md and the blocked pattern list in README.md from the rule catalog and
// the mapping tables. The Playwright column is printed by the real emitter, so the docs show
// exactly what `migrate` writes. Run `npm run docs:generate` after changing a table or a rule.
import path from 'node:path';
import { format, resolveConfig } from 'prettier';
import type { ActionStep, AssertStep, Locator, Step } from '../core/ir.js';
import { RULES } from '../core/rules.js';
import type { RuleDefinition, RuleSource } from '../core/rules.js';
import { PRETTIER_OPTIONS, stepLines } from '../emit/playwright.js';
import {
  ACTIONS,
  CALLBACK_METHODS,
  ELEMENT_ASSERTIONS,
  TITLE_ASSERTIONS,
  URL_ASSERTIONS,
} from '../sources/cypress-js/table.js';
import type { AssertionRow } from '../sources/cypress-js/table.js';
import {
  assertStep,
  BY_NAMES,
  byLocator,
  KEYS,
  waitResult,
  WAIT_CONDITIONS,
} from '../sources/selenium/common.js';
import type { ByKind } from '../sources/selenium/common.js';
import { withStatus } from '../sources/shared.js';

export const MAPPING_DOC = 'docs/mapping.md';
export const README_BLOCK_START = '<!-- block-rules:start (generated by npm run docs:generate) -->';
export const README_BLOCK_END = '<!-- block-rules:end -->';

const SPAN = { startLine: 1, endLine: 1, startColumn: 0, text: '' };
const ELEMENT: Locator = { strategy: 'css', value: '#element', chain: [] };

const SOURCE_LABELS: Record<RuleSource, string> = {
  all: 'All sources',
  'cypress-js': 'Cypress JS',
  selenium: 'Selenium Python and Java',
  'selenium-python': 'Selenium Python',
  'selenium-java': 'Selenium Java',
};

const code = (text: string): string => `\`${text}\``;
const cell = (text: string): string => text.replace(/\|/g, '\\|');
// Plain text from the rule catalog, escaped so Markdown shows it as written.
const prose = (text: string): string => text.replace(/([\\`*_[\]<>])/g, '\\$1');

function playwright(step: Step): string {
  const { code: lines } = stepLines(step);
  return lines.length > 0 ? code(lines.join(' ')) : 'Removed';
}

function action(row: (typeof ACTIONS)[string], value?: string): ActionStep {
  const step: Omit<ActionStep, 'status'> = {
    kind: 'action',
    action: row.action,
    target: ELEMENT,
    span: SPAN,
    flags: [],
  };
  if (row.action === 'selectOption') step.select = { by: 'valueOrLabel', value: value ?? '' };
  else if (value !== undefined) step.value = value;
  return withStatus(step);
}

function sampleExpected(row: AssertionRow): Partial<AssertStep> {
  switch (row.args) {
    case 'none':
      return {};
    case 'value':
      return { expected: 'expected' };
    case 'number':
      return { expected: 3 };
    case 'attribute':
      return { attribute: 'name', expected: 'value' };
  }
}

function cypressAssertion(row: AssertionRow, target: Locator | 'page'): string {
  return playwright(
    withStatus({
      kind: 'assert',
      assertion: row.assertion,
      target,
      negated: false,
      origin: 'assertion',
      span: SPAN,
      flags: [],
      ...sampleExpected(row),
    } as AssertStep),
  );
}

function table(head: string[], rows: string[][]): string[] {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
    '',
  ];
}

function ruleRows(rules: readonly RuleDefinition[]): string[][] {
  return rules.map((r) => [
    code(r.id),
    r.level,
    SOURCE_LABELS[r.appliesTo],
    prose(r.title),
    prose(r.message),
  ]);
}

const BY_SAMPLES: Record<ByKind, string> = {
  id: 'login-button',
  className: 'title',
  name: 'user-name',
  tagName: 'h1',
  css: '[data-test="title"]',
  xpath: '//h1',
  linkText: 'Sauce Labs Backpack',
  partialLinkText: 'Backpack',
};

function bySection(): string[] {
  const kinds = [...new Set(Object.values(BY_NAMES))];
  const rows = kinds.map((kind) => {
    const names = Object.keys(BY_NAMES).filter((n) => BY_NAMES[n] === kind);
    const python = names.filter((n) => n === n.toUpperCase());
    const java = names.filter((n) => n !== n.toUpperCase());
    const found = byLocator(kind, BY_SAMPLES[kind], 1);
    const step = action({ action: 'click' });
    step.target = found.locator;
    const notes = found.notes.map((f) => code(f.ruleId)).join(', ');
    return [
      python.map((n) => code(`By.${n}`)).join(', '),
      java.map((n) => code(`By.${n}`)).join(', '),
      code(BY_SAMPLES[kind]),
      playwright(step),
      notes || 'None',
    ];
  });
  return table(['Python', 'Java', 'Sample value', 'Playwright (sample click)', 'Flags'], rows);
}

function conditionSection(): string[] {
  const found = { locator: ELEMENT, notes: [] };
  const rows = Object.entries(WAIT_CONDITIONS).map(([name, row]) => {
    const language = name.includes('_') ? 'Python' : 'Java';
    let result: string;
    if ('blocked' in row) {
      result = `Blocked: ${code(row.blocked)}`;
    } else if (row.assertion === 'clickable') {
      result = `Removed with ${code('CORE_CLICKABLE_WAIT_REMOVED')} when the next step acts on the same element; otherwise blocked with ${code('CORE_CUSTOM_WAIT')}`;
    } else {
      const text = row.args === 'found' ? undefined : 'expected';
      const wait = waitResult(row, row.args === 'text' ? undefined : found, text, false);
      result = 'spec' in wait ? playwright(assertStep(wait.spec, SPAN, 'wait')) : '';
    }
    return [code(name), language, result];
  });
  return table(['Expected condition', 'Language', 'Playwright'], rows);
}

// Formats every Playwright code span the way `migrate` formats a spec, so the quotes match.
async function formatCodeSpans(markdown: string): Promise<string> {
  const spans = [...new Set(markdown.match(/`await [^`]+`/g) ?? [])];
  const formatted = new Map<string, string>();
  for (const span of spans) {
    const out = await format(span.slice(1, -1), PRETTIER_OPTIONS);
    formatted.set(span, code(out.trim()));
  }
  return markdown.replace(/`await [^`]+`/g, (span) => formatted.get(span) ?? span);
}

// The full mapping reference, formatted with the Prettier config of the repo at root.
export async function renderMappingReference(root: string = process.cwd()): Promise<string> {
  const lines = [
    '# Mapping Reference',
    '',
    'Generated by `npm run docs:generate` from the rule catalog (`src/core/rules.ts`) and the mapping tables (`src/sources/cypress-js/table.ts` and `src/sources/selenium/common.ts`). Do not edit it by hand. A unit test fails when this file and the tables differ.',
    '',
    'The Playwright column is printed by the same emitter that `migrate` uses, with `#element` as the sample locator. Navigation, locator chains and test structure are converted by the extractors and are covered by the fixtures and tests, not by these tables.',
    '',
    '## Rules',
    '',
    'Every flag in a migration report has one of these rule IDs. INFO means the step was converted with a note. WARN means it was converted but needs a look. BLOCK means it was not converted, and the test is emitted as `test.fixme`.',
    '',
    ...table(['Rule', 'Level', 'Applies to', 'Title', 'Message'], ruleRows(RULES)),
    '## Cypress JS Actions',
    '',
    ...table(
      ['Cypress', 'Playwright', 'Flags'],
      Object.entries(ACTIONS).map(([name, row]) => {
        const value = name === 'type' || name === 'select' ? 'value' : undefined;
        const source = `cy.get('#element').${name}(${value === undefined ? '' : `'${value}'`})`;
        return [code(source), playwright(action(row, value)), row.info ? code(row.info) : 'None'];
      }),
    ),
    '## Cypress JS Assertions',
    '',
    'Each chainer can be negated with a `not.` prefix, which adds `.not` to the Playwright assertion.',
    '',
    ...table(
      ['Subject', 'Chainer', 'Playwright'],
      [
        ...Object.entries(ELEMENT_ASSERTIONS).map(([chainer, row]) => [
          code("cy.get('#element')"),
          code(chainer),
          cypressAssertion(row, ELEMENT),
        ]),
        ...Object.entries(URL_ASSERTIONS).map(([chainer, row]) => [
          code('cy.url()'),
          code(chainer),
          cypressAssertion(row, 'page'),
        ]),
        ...Object.entries(TITLE_ASSERTIONS).map(([chainer, row]) => [
          code('cy.title()'),
          code(chainer),
          cypressAssertion(row, 'page'),
        ]),
      ],
    ),
    '## Cypress JS Callbacks',
    '',
    `${CALLBACK_METHODS.map((m) => code(`.${m}()`)).join(', ')} and \`should\` with a function are blocked with \`CY_THEN\`. A \`cy.<name>\` call that is not a built-in Cypress command is blocked with \`CY_CUSTOM_COMMAND\`, and a built-in command with no mapping is blocked with \`CY_UNSUPPORTED_COMMAND\`.`,
    '',
    '## Selenium Locators',
    '',
    ...bySection(),
    '## Selenium Expected Conditions',
    '',
    'A wait such as `WebDriverWait(driver, 10).until(...)` becomes a web-first assertion. `until_not` and `until(not(...))` add `.not`.',
    '',
    ...conditionSection(),
    '## Selenium Keys',
    '',
    ...table(
      ['Keys constant', 'Playwright'],
      Object.entries(KEYS).map(([name, key]) => [
        code(`Keys.${name}`),
        playwright(action({ action: 'press' }, key)),
      ]),
    ),
  ];
  const text = await formatCodeSpans(lines.join('\n'));
  const filepath = path.join(root, MAPPING_DOC);
  const config = (await resolveConfig(filepath)) ?? {};
  return format(text, { ...config, filepath });
}

// The list of BLOCK rules for the README, between the two markers.
export function renderBlockRuleList(): string {
  const rules = RULES.filter((r) => r.level === 'BLOCK');
  return [
    README_BLOCK_START,
    '',
    ...rules.map(
      (r) =>
        `- \`${r.id}\` (${SOURCE_LABELS[r.appliesTo]}): ${prose(r.title)}. ${prose(r.message)}`,
    ),
    '',
    README_BLOCK_END,
  ].join('\n');
}

// The README with its generated block replaced. Throws when the markers are missing.
export function replaceReadmeBlock(readme: string): string {
  const start = readme.indexOf(README_BLOCK_START);
  const end = readme.indexOf(README_BLOCK_END);
  if (start < 0 || end < start) throw new Error('README.md has no block-rules markers.');
  return (
    readme.slice(0, start) + renderBlockRuleList() + readme.slice(end + README_BLOCK_END.length)
  );
}
